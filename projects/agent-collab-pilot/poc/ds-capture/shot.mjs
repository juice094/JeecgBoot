import { spawn } from 'node:child_process';
import fs from 'node:fs';
const chrome = spawn('google-chrome', ['--headless=new','--no-sandbox','--disable-gpu','--remote-debugging-port=0','--user-data-dir=/tmp/dscap-shot-'+Date.now(),'--window-size=1280,900','about:blank'],{stdio:['ignore','pipe','pipe']});
const wsUrl = await new Promise((res,rej)=>{let b='';chrome.stderr.on('data',d=>{b+=d;const m=b.match(/DevTools listening on (ws:\/\/\S+)/);if(m)res(m[1]);});setTimeout(()=>rej(new Error('timeout')),20000);});
const ws = new WebSocket(wsUrl); await new Promise(r=>ws.onopen=r);
let id=0;const pend=new Map();
const send=(m,p={},s)=>new Promise((res,rej)=>{const i=++id;pend.set(i,{res,rej});ws.send(JSON.stringify({id:i,method:m,params:p,sessionId:s}));});
ws.onmessage=ev=>{const m=JSON.parse(ev.data);if(m.id&&pend.has(m.id)){const{res,rej}=pend.get(m.id);pend.delete(m.id);m.error?rej(new Error(JSON.stringify(m.error))):res(m.result);}};
const {targetId}=await send('Target.createTarget',{url:'about:blank'});
const {sessionId}=await send('Target.attachToTarget',{targetId,flatten:true});
await send('Page.enable',{},sessionId);await send('Runtime.enable',{},sessionId);
await send('Page.navigate',{url:'https://chat.deepseek.com/'},sessionId);
await new Promise(r=>setTimeout(r,12000));
const info=await send('Runtime.evaluate',{expression:'JSON.stringify({title:document.title,len:document.documentElement.outerHTML.length,body:document.body?document.body.innerText.slice(0,200):"no-body"})',returnByValue:true},sessionId);
console.log('PAGE:',info.result.value);
const shot=await send('Page.captureScreenshot',{format:'png'},sessionId);
fs.writeFileSync('page-evidence.png',Buffer.from(shot.data,'base64'));
console.log('screenshot saved');
try{await send('Browser.close');}catch{} chrome.kill('SIGKILL'); process.exit(0);
